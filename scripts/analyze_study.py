"""Analyze every experiment that has outputs and write reports/tables, reports/figures, reports/results.md and the
aggregated data file the website demo reads (reports/demo_data.json; portfolio-level series only, no stock data).

    python scripts/analyze_study.py [--bootstrap 5000]
"""
from __future__ import annotations

import argparse
import json
import sys
import time
from pathlib import Path

import numpy as np
import pandas as pd

sys.path.insert(0, str(Path(__file__).parent))
import run_study as rs                                            # noqa: E402

from alphacomb import analysis as A                               # noqa: E402
from alphacomb import figures as F                                # noqa: E402
from alphacomb import models, paths, study                        # noqa: E402
from alphacomb.evaluation import metrics, stats                   # noqa: E402
from alphacomb.registry import Registry                           # noqa: E402
from alphacomb.reporting import md_table                          # noqa: E402

T_DIR, F_DIR = paths.REPORTS / "tables", paths.REPORTS / "figures"
SCALE_FREE = {"EW", "HEW", "ICW", "MVO", "ONLINE_EG"}


def pct(x, nd=1):
    return "" if x is None or not np.isfinite(x) else f"{100 * x:.{nd}f}%"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--bootstrap", type=int, default=5000)
    a = ap.parse_args()
    t0 = time.time()
    T_DIR.mkdir(parents=True, exist_ok=True)
    F_DIR.mkdir(parents=True, exist_ok=True)
    cfg, p, mom = rs.real_inputs()
    B, block = a.bootstrap, cfg["inference"]["block"]
    ff = pd.read_parquet(paths.PROCESSED / "factors_monthly.parquet")
    order = [m for m in models.ORDER if (paths.RESULTS / "main" / f"{m}.pkl").exists()]
    res = {m: study.load(paths.RESULTS / "main" / f"{m}.pkl") for m in order}
    months = res["EW"].months
    md = ["# Results (generated by scripts/analyze_study.py)", "",
          f"Out-of-sample formation months {p.dates[months[0]].date()} to {p.dates[months[-1]].date()} "
          f"({len(months)} months; returns earned the following month). Rank-weighted dollar-neutral long-short "
          "portfolios; net = after the base cost schedule.", ""]

    # ------------------------------------------------------------------ E2: per-method table
    ev = {m: A.Evaluated(m, r.pred, p, r.months, r.weights) for m, r in res.items()}
    sig_ev = {k: A.Evaluated(k, v, p, months, keep_trades=False) for k, v in A.single_signal_preds(p).items()}
    rows = {}
    for k, e in {**ev, **sig_ev}.items():
        row = A.summary_row(e, p, ff)
        lo, hi = A.sharpe_ci(e.net[months], B, block, seed=1)
        row.update(sharpe_net_lo=lo, sharpe_net_hi=hi)
        if k in res:
            row["r2_oos_bp"] = 1e4 * A.calibrated_r2(e.pred, p, months, res[k].weights, mom, k in SCALE_FREE)
            row["kind"] = models.METHODS[k].kind
        else:
            row["kind"] = "signal"
        rows[k] = row
    tab = pd.DataFrame(rows).T
    tab.index.name = "method"
    tab.to_csv(T_DIR / "main_methods.csv")
    cols = ["rank_ic", "rank_ic_t", "r2_oos_bp", "gross_ret", "sharpe_gross", "sharpe_net", "sharpe_net_lo",
            "sharpe_net_hi", "sharpe_net_high", "max_dd_net", "turnover", "breakeven_mult", "alpha", "alpha_t"]
    md += ["## E2: every method, 1980-2024", "", md_table(tab.loc[order, cols].astype(float),
           {"rank_ic": 4, "rank_ic_t": 1, "r2_oos_bp": 1, "turnover": 1, "breakeven_mult": 1, "alpha_t": 1}), "",
           "Single signals (each signal alone, same portfolio rule):", "",
           md_table(tab.loc[list(sig_ev), ["rank_ic", "rank_ic_t", "sharpe_gross", "sharpe_net", "turnover"]]
                    .astype(float), {"rank_ic": 4, "rank_ic_t": 1, "turnover": 1}), ""]

    # ------------------------------------------------------------------ H1/H2 and H3
    tests = A.tests_vs(ev, "EW", B, block, seed=11)
    tests.to_csv(T_DIR / "tests_vs_ew.csv")
    complex_m = [m for m in order if m not in cfg["simple_methods"]]
    spa_c = A.spa(ev, "EW", complex_m, B, block, seed=21)
    spa_all = A.spa(ev, "EW", [m for m in order if m != "EW"], B, block, seed=31)
    hew = A.tests_vs({k: ev[k] for k in order}, "HEW", B, block, seed=41)
    hew.to_csv(T_DIR / "tests_vs_hew.csv")
    md += ["## H1/H2: each method against equal weights", "",
           md_table(tests[["sharpe_diff", "sharpe_ci_lo", "sharpe_ci_hi", "p_sharpe", "p_sharpe_holm", "p_sharpe_rw",
                           "ic_diff", "ic_t", "p_ic", "p_ic_holm", "p_ic_rw", "corr_with_bench"]].astype(float),
                    {"ic_diff": 4, "ic_t": 2, "p_sharpe": 3, "p_sharpe_holm": 3, "p_sharpe_rw": 3, "p_ic": 3,
                     "p_ic_holm": 3, "p_ic_rw": 3}), "",
           "## H3: Hansen SPA, best method vs equal weights", ""]
    for lab, s in (("complex methods", spa_c), ("all methods", spa_all)):
        for metric, r in s.items():
            md.append(f"- {lab}, {metric}: best {r['best']}, consistent p = {r['p_consistent']:.3f} "
                      f"(lower {r['p_lower']:.3f}, upper {r['p_upper']:.3f})")
    md.append("")
    reg_mi = Registry()

    # ------------------------------------------------------------------ H7, subperiods, regimes
    d = np.nan_to_num(ev["REGIME"].ic[months] - ev["OLS"].ic[months])
    h7 = {"ic_diff": float(d.mean()), "t": stats.nw_tstat(d)}
    md += ["## H7: REGIME vs OLS (rank IC)", "",
           f"Mean monthly difference {h7['ic_diff']:.4f}, Newey-West t = {h7['t']:.2f}.", ""]
    sp = A.subperiods(ev, p, cfg["subperiods"])
    sp.to_csv(T_DIR / "subperiods.csv", index=False)
    piv = sp.pivot(index="method", columns="period", values="sharpe_net").loc[order]
    piv_ic = sp.pivot(index="method", columns="period", values="rank_ic").loc[order]
    from alphacomb.evaluation.stability import rank_stability
    rs_net = rank_stability(piv.T)
    piv_ic2 = piv_ic.add_suffix(" IC")
    md += ["## Subperiods (net Sharpe | rank IC)", "", md_table(piv.join(piv_ic2).astype(float),
                                                                {c: 4 for c in piv_ic2.columns}), "",
           f"Method-ranking concordance across subperiods (net Sharpe): Kendall W = {rs_net['kendall_w']:.2f}, "
           f"mean pairwise tau = {rs_net['mean_tau']:.2f}.", ""]
    rg = A.regimes(ev, p)
    rg.to_csv(T_DIR / "regimes.csv", index=False)
    rp = rg.pivot(index="method", columns="slice", values="ic_minus_bench").loc[order]
    md += ["## Regimes: rank IC minus equal weights", "", md_table(rp.astype(float), 4), ""]

    # ------------------------------------------------------------------ stability, importance, capacity
    st = A.stability_table(res, ev)
    st.to_csv(T_DIR / "stability.csv")
    md += ["## Stability", "", md_table(st[["weight_corr_refits", "sign_flip_rate", "monthly_weight_turnover",
                                            "tunings", "selection_change_rate", "modal_selection", "modal_share"]],
                                        {"modal_share": 2}), ""]
    imp = A.importance_table(res)
    imp.to_csv(T_DIR / "importance.csv")
    fam_cols = [c for c in imp.columns if c.startswith("family:")]
    md += ["## Permutation importance by family (drop in mean rank IC)", "",
           md_table(imp.loc[[m for m in order if m in imp.index], fam_cols].astype(float), 4), ""]
    cap_rows = {}
    aum_grid = [float(x) for x in cfg["costs"]["aum_grid"]]      # YAML 1.1 reads 1.0e7 as a string
    for m in order:
        cap = A.capacity(ev[m], p, aum_grid, float(cfg["costs"]["impact_y"]))
        cap_rows[m] = {f"${x / 1e9:g}B": v["sharpe_net"] for x, v in cap.items()} | {
            "breakeven_aum_$B": A.breakeven_aum(cap) / 1e9}
    capt = pd.DataFrame(cap_rows).T
    capt.to_csv(T_DIR / "capacity.csv")
    md += ["## Capacity: net Sharpe by assets under management (square-root impact)", "",
           md_table(capt.astype(float), 2), ""]
    for m in order:
        if np.isfinite(res[m].weights[months]).all():
            A.weights_by_year(res[m], p).to_csv(T_DIR / f"weights_{m}.csv")

    # ------------------------------------------------------------------ figures (E2)
    idx = p.dates[months] + pd.offsets.MonthEnd(1)
    net = {m: pd.Series(ev[m].net[months], index=idx) for m in order}
    F.cumulative(net, "Growth of $1, net of costs, 1980-2024 (gray: the other methods)",
                 F_DIR / "cumulative_net.png", highlight=["EW", "RIDGE", "GBM", "RF"])
    dd = tab.loc[order, ["sharpe_net", "sharpe_net_lo", "sharpe_net_hi"]].astype(float)
    F.dot_ci(dd, "sharpe_net", "sharpe_net_lo", "sharpe_net_hi", "Net Sharpe ratio with 95% bootstrap interval",
             "annualized Sharpe ratio, net of base costs", F_DIR / "sharpe_net_ci.png",
             ref=float(dd.loc["EW", "sharpe_net"]), ref_label="equal weights")
    td = tests.loc[[m for m in order if m != "EW"], ["sharpe_diff", "sharpe_ci_lo", "sharpe_ci_hi"]].astype(float)
    F.dot_ci(td, "sharpe_diff", "sharpe_ci_lo", "sharpe_ci_hi", "Net Sharpe minus equal weights (95% interval)",
             "difference in annualized Sharpe ratio", F_DIR / "sharpe_diff_vs_ew.png", ref=0.0, ref_label="")
    fam_imp = imp.loc[[m for m in order if m in imp.index], fam_cols].astype(float)
    fam_imp.columns = [c.split(":")[1] for c in fam_cols]
    F.heatmap(fam_imp, "Out-of-sample permutation importance by signal family", F_DIR / "importance_families.png",
              fmt="{:.3f}", cbar_label="drop in mean rank IC")
    wy = {m: A.weights_by_year(res[m], p) for m in ("OLS", "BSHRINK", "DMA") if m in res}
    for m, w in wy.items():
        fam = p.family_index()
        wf = pd.DataFrame({f: w.iloc[:, idx_].sum(1) for f, idx_ in fam.items()})
        F.lines(wf, f"{m}: weight on each signal family by year (normalized, |w| sums to 1)",
                F_DIR / f"family_weights_{m}.png", ylabel="weight")

    # ------------------------------------------------------------------ E3 robustness
    rob = {}
    for variant in ("rolling120", "rule1se"):
        dr = paths.RESULTS / "robust" / variant
        if dr.exists() and any(dr.glob("*.pkl")):
            r_ = A.load_dir(dr)
            e_ = {m: A.Evaluated(m, r.pred, p, r.months, r.weights, keep_trades=False) for m, r in r_.items()}
            if "EW" not in e_:
                e_["EW"] = ev["EW"]
            rows_ = {m: {"rank_ic": float(np.nanmean(e.ic[months])), "sharpe_net": stats.sharpe(e.net[months])}
                     for m, e in e_.items()}
            tv = A.tests_vs(e_, "EW", min(B, 2000), block, seed=51)
            df = pd.DataFrame(rows_).T.join(tv[["sharpe_diff", "p_sharpe", "ic_diff", "p_ic"]])
            df = df.loc[[m for m in order if m in df.index]]
            df.to_csv(T_DIR / f"robust_{variant}.csv")
            rob[variant] = df
            md += [f"## E3 robustness: {variant}", "", md_table(df.astype(float), {"rank_ic": 4, "ic_diff": 4,
                                                                                  "p_sharpe": 3, "p_ic": 3}), ""]
    qt = tab.loc[order, ["q_sharpe_gross", "q_sharpe_net", "q_turnover", "sharpe_net_high"]].astype(float)
    md += ["## E3 robustness: quintile portfolios and high costs", "", md_table(qt, 2), ""]

    # ------------------------------------------------------------------ E5 real time
    rt_dir = paths.RESULTS / "realtime"
    if rt_dir.exists() and (rt_dir / "EW.pkl").exists():
        rt = A.load_dir(rt_dir)
        ert = {m: A.Evaluated(m, r.pred, p, r.months, r.weights, keep_trades=False) for m, r in rt.items()}
        trt = A.tests_vs(ert, "EW", min(B, 2000), block, seed=61)
        trt.to_csv(T_DIR / "realtime_tests.csv")
        rrow = pd.DataFrame({m: {"rank_ic": float(np.nanmean(e.ic[months])), "sharpe_net": stats.sharpe(e.net[months])}
                             for m, e in ert.items()}).T
        rrow = rrow.loc[[m for m in order if m in rrow.index]].join(
            trt[["sharpe_diff", "p_sharpe_holm", "ic_diff", "p_ic_holm"]])
        rrow.to_csv(T_DIR / "realtime_methods.csv")
        gap = stats.sharpe_diff_test(ev["EW"].net[months], ert["EW"].net[months], B=min(B, 2000), block=block)
        md += ["## E5 real-time signal availability", "", md_table(rrow.astype(float), {"rank_ic": 4, "ic_diff": 4,
                                                                                       "p_sharpe_holm": 3,
                                                                                       "p_ic_holm": 3}), "",
               f"Hindsight EW minus real-time EW: net Sharpe difference {gap['diff']:.2f} "
               f"[{gap['ci_lo']:.2f}, {gap['ci_hi']:.2f}], p = {gap['p_boot']:.3f}.", ""]

    # ------------------------------------------------------------------ E6 complexity + PBO
    cx_dir = paths.RESULTS / "complexity"
    pbo = None
    if cx_dir.exists() and any(cx_dir.glob("*.pkl")):
        cx = A.complexity_frame(cx_dir)
        cx.to_csv(T_DIR / "complexity.csv", index=False)
        frames, h6 = {}, {}
        for meth, g in cx.groupby("method"):
            grid = models.METHODS[meth].grid
            tags = ["_".join(f"{k}{v}" for k, v in c.items()) for c in grid]
            g = g.set_index("config").reindex(tags).dropna(subset=["rank_ic"]).reset_index()
            g["complexity_rank"] = np.arange(len(g))
            frames[meth] = g
            from scipy.stats import spearmanr
            h6[meth] = float(spearmanr(g["complexity_rank"], g["rank_ic"]).statistic) if len(g) > 2 else np.nan
        F.small_multiples({k: v for k, v in frames.items()}, "complexity_rank", "rank_ic",
                          "Out-of-sample rank IC as each method's complexity rises (fixed hyperparameters; line = EW)",
                          F_DIR / "complexity_curves.png", ref=float(np.nanmean(ev["EW"].ic[months])),
                          xlabel="grid position (left = most regularized)", ylabel="mean rank IC")
        R = A.complexity_returns(cx_dir).dropna()
        pbo = stats.pbo_cscv(R.to_numpy(), S=16)
        md += ["## E6 complexity (H6) and PBO (H5)", "",
               "Spearman correlation between grid position (more complex to the right) and out-of-sample rank IC: "
               + ", ".join(f"{k} {v:+.2f}" for k, v in h6.items()) + ".", "",
               f"PBO over {pbo['n_strategies']} fixed configurations ({pbo['n_splits']} CSCV splits, 16 blocks): "
               f"{pbo['pbo']:.2f}; probability the in-sample best loses money out of sample {pbo['p_oos_loss']:.2f}; "
               f"slope of out-of-sample on in-sample Sharpe {pbo['degradation_slope']:.2f}.", ""]
        json.dump({"h6": h6, "pbo": {k: v for k, v in pbo.items() if not isinstance(v, np.ndarray)}},
                  open(T_DIR / "complexity_pbo.json", "w"), indent=1)

    # ------------------------------------------------------------------ E4 leakage
    lk = {s: paths.RESULTS / "leakage" / s for s in ("purged_kfold", "naive_kfold")}
    if all(d.exists() and any(d.glob("*.pkl")) for d in lk.values()):
        lf = A.leakage_frame(res, lk, p)
        lf.to_csv(T_DIR / "leakage.csv", index=False)
        agg = lf.groupby(["method", "scheme"])[["inner_ic", "realized_ic", "optimism"]].mean().unstack("scheme")
        md += ["## E4 leakage: inner-validation optimism by CV scheme", "", md_table(agg.round(4).astype(float), 4),
               ""]
        for meth in ("RIDGE", "ENET", "GBM"):
            sub = lf[lf["method"] == meth].pivot(index="refit", columns="scheme", values="optimism")
            if {"naive_kfold", "forward"} <= set(sub.columns):
                dd_ = (sub["naive_kfold"] - sub["forward"]).dropna()
                if len(dd_) > 2:
                    t = dd_.mean() / (dd_.std(ddof=1) / np.sqrt(len(dd_)))
                    md.append(f"- {meth}: naive minus forward optimism {dd_.mean():+.4f} (t = {t:.2f}, "
                              f"{len(dd_)} tuning events)")
        md.append("")

    # ------------------------------------------------------------------ H4 DSR (all real-data trials)
    trial_series = {f"main/{m}": ev[m].net[months] for m in order}
    for sub in ("robust/rolling120", "robust/rule1se", "realtime", "exploratory"):
        dsub = paths.RESULTS / sub
        if dsub.exists():
            for f in dsub.glob("*.pkl"):
                r = study.load(f)
                trial_series[f"{sub}/{f.stem}"] = A.Evaluated(f.stem, r.pred, p, r.months, keep_trades=False).net[months]
    for sub in ("complexity", "leakage/purged_kfold", "leakage/naive_kfold"):
        dsub = paths.RESULTS / sub
        if dsub.exists():
            for f in dsub.glob("*.pkl"):
                s = study.load(f)
                trial_series[f"{sub}/{f.stem}"] = s["net"][months]
    Rm = np.column_stack(list(trial_series.values()))
    srs = np.nanmean(Rm, 0) / np.nanstd(Rm, 0, ddof=1)
    n_reg = reg_mi.trials("real/")
    eff = stats.effective_trials(np.nan_to_num(Rm))
    best = tab.loc[order, "sharpe_net"].astype(float).idxmax()
    d_all = stats.dsr(ev[best].net[months], max(n_reg, len(trial_series)), float(np.var(srs, ddof=1)))
    d_eff = stats.dsr(ev[best].net[months], eff["participation_ratio"], float(np.var(srs, ddof=1)))
    md += ["## H4: deflated Sharpe ratio of the best method", "",
           f"Best net Sharpe: {best} ({stats.sharpe(ev[best].net[months]):.2f} annualized). Trials: {n_reg} distinct "
           f"completed real-data configurations in the registry; {len(trial_series)} return series on disk; their "
           f"effective number (participation ratio) {eff['participation_ratio']:.1f}, mean pairwise correlation "
           f"{eff['mean_corr']:.2f}.",
           f"- DSR with N = {max(n_reg, len(trial_series))}: {d_all['dsr']:.3f} (expected max Sharpe under the null "
           f"{d_all['sr0'] * np.sqrt(12):.2f} annualized)",
           f"- DSR with N = effective {eff['participation_ratio']:.1f}: {d_eff['dsr']:.3f}", ""]

    # ------------------------------------------------------------------ E1 synthetic
    sy_dir = paths.RESULTS / "synthetic"
    if sy_dir.exists() and any(sy_dir.glob("*.pkl")):
        sy = A.synthetic_frame(sy_dir)
        sy.to_csv(T_DIR / "synthetic.csv", index=False)
        agg = sy.groupby(["dgp", "ic", "method"])["ratio"].mean().unstack("method")
        agg = agg[[m for m in models.ORDER if m in agg.columns]]
        agg.to_csv(T_DIR / "synthetic_ratio.csv")
        md += ["## E1 synthetic positive controls: OOS rank IC as a share of the oracle's", "",
               md_table(agg.round(3).astype(float), 2), ""]
        for icv in sorted(sy["ic"].unique()):
            M = agg.xs(icv, level="ic")
            F.heatmap(M, f"Synthetic panels, oracle IC {icv:g}: out-of-sample rank IC / oracle rank IC",
                      F_DIR / f"synthetic_ratio_ic{icv:g}.png", fmt="{:.2f}", cbar_label="share of oracle")

    (paths.REPORTS / "results.md").write_text("\n".join(md), encoding="utf-8")
    export_demo(cfg, p, ev, sig_ev, tab, tests, spa_c, order, months, pbo)
    print(f"analysis written in {time.time() - t0:.0f}s")


def export_demo(cfg, p, ev, sig_ev, tab, tests, spa_c, order, months, pbo) -> None:
    """Aggregated series for the website demo: monthly portfolio returns and ICs, yearly weights, summary stats."""
    idx = [str((d + pd.offsets.MonthEnd(1)).date())[:7] for d in p.dates[months]]

    def r4(a):
        return [None if not np.isfinite(x) else round(float(x), 5) for x in a]

    methods = {}
    for m in order:
        e = ev[m]
        w = A.weights_by_year(type("R", (), {"weights": e.weights, "months": months})(), p) \
            if e.weights is not None and np.isfinite(e.weights[months]).all() else None
        t = tests.loc[m] if m in tests.index else None
        methods[m] = {"label": models.METHODS[m].label, "kind": models.METHODS[m].kind,
                      "net": r4(e.net[months]), "gross": r4(e.gross[months]), "ic": r4(e.ic[months]),
                      "turnover": r4(e.turnover[months]),
                      "weights_by_year": None if w is None else {"years": [int(y) for y in w.index],
                                                                 "w": [r4(row) for row in w.to_numpy()]},
                      "stats": {k: (None if not np.isfinite(float(v)) else round(float(v), 4))
                                for k, v in tab.loc[m].drop("kind").items()},
                      "vs_ew": None if t is None else {k: round(float(t[k]), 4) for k in
                                                       ("sharpe_diff", "sharpe_ci_lo", "sharpe_ci_hi", "p_sharpe",
                                                        "p_sharpe_holm", "ic_diff", "p_ic", "p_ic_holm")}}
    corr = pd.read_csv(T_DIR / "signal_correlation.csv", index_col=0)
    extra = {}
    hf = T_DIR / "exploratory_market_hedged.csv"
    if hf.exists():
        h = pd.read_csv(hf, index_col=0)
        extra["hedged"] = {m: {"unhedged": round(float(h.loc[m, "sharpe_net"]), 3),
                               "hedged": round(float(h.loc[m, "sharpe_hedged"]), 3)} for m in h.index}
    mf = T_DIR / "exploratory_mvo_decomposition.csv"
    if mf.exists():
        d = pd.read_csv(mf, index_col=0)
        extra["mvo_decomposition"] = {m: {"rank_ic": round(float(d.loc[m, "rank_ic"]), 4),
                                          "sharpe_net": round(float(d.loc[m, "sharpe_net"]), 3)} for m in d.index}
    sp = pd.read_csv(T_DIR / "subperiods.csv")
    extra["subperiods"] = {per: {r.method: {"sharpe_net": round(float(r.sharpe_net), 3), "rank_ic": round(float(r.rank_ic), 4)}
                                 for r in g.itertuples()} for per, g in sp.groupby("period")}
    out = {**extra, "months": idx, "signals": p.names, "families": p.families,
           "signal_stats": {k.split(":")[1]: {"rank_ic": round(float(tab.loc[k, "rank_ic"]), 4),
                                              "sharpe_net": round(float(tab.loc[k, "sharpe_net"]), 3)}
                            for k in sig_ev},
           "signal_corr": corr.round(3).to_numpy().tolist(), "methods": methods, "order": order,
           "spa_complex": {k: {kk: (round(vv, 4) if isinstance(vv, float) else vv) for kk, vv in v.items()}
                           for k, v in spa_c.items()},
           "pbo": None if pbo is None else round(float(pbo["pbo"]), 3),
           "regime": p.month_info["regime"].reindex(p.dates[months]).fillna("").tolist()}
    (paths.REPORTS / "demo_data.json").write_text(json.dumps(out, separators=(",", ":")), encoding="utf-8")


if __name__ == "__main__":
    main()
