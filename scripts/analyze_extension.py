"""Analyze the signal extension (experiments/preregistration_extension.md): H10 (do analyst and options signals add
information to equal weights?), H11 (does any complex method beat extended equal weights?), H12 (the same after an
ex-ante market hedge), and the descriptive comparisons. Writes reports/extension.md and reports/tables/ext_*.csv.

    python scripts/analyze_extension.py [--bootstrap 5000]
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd

sys.path.insert(0, str(Path(__file__).parent))
import run_study as rs                                            # noqa: E402

from alphacomb import analysis as A                               # noqa: E402
from alphacomb import figures as F                                # noqa: E402
from alphacomb import models, paths, study                        # noqa: E402
from alphacomb.evaluation import stats                            # noqa: E402
from alphacomb.reporting import md_table                          # noqa: E402

T_DIR, F_DIR = paths.REPORTS / "tables", paths.REPORTS / "figures"
WINDOWS = {"a": ("ext_a", "ext_a_base", "analyst signals added, 1990-2024"),
           "b": ("ext_b", "ext_b_base", "analyst and options signals added, 2004-2024")}


def load(config: str):
    cfg, p, mom = rs.real_inputs(config)
    order = [m for m in models.ORDER if (paths.RESULTS / config / f"{m}.pkl").exists()]
    res = {m: study.load(paths.RESULTS / config / f"{m}.pkl") for m in order}
    ev = {m: A.Evaluated(m, r.pred, p, r.months, r.weights, keep_trades=False) for m, r in res.items()}
    return cfg, p, res, ev, order


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--bootstrap", type=int, default=5000)
    ap.add_argument("--demo-only", action="store_true", help="only rewrite reports/demo_extension.json from saved tables")
    a = ap.parse_args()
    if a.demo_only:
        export_demo()
        return
    B, block = a.bootstrap, 6
    ff = pd.read_parquet(paths.PROCESSED / "factors_monthly.parquet")
    md = ["# Signal extension: results (generated by scripts/analyze_extension.py)", "",
          "Pre-registered in experiments/preregistration_extension.md (commit 0a0ce07) before any run.", ""]
    h10_rows, summary = [], {}
    for w, (ext, base, label) in WINDOWS.items():
        cfg_e, p_e, res_e, ev_e, order_e = load(ext)
        cfg_b, p_b, res_b, ev_b, order_b = load(base)
        months = ev_e["EW"].months
        assert np.array_equal(months, ev_b["EW"].months), "extended and baseline windows differ"
        earn = p_e.dates + pd.offsets.MonthEnd(1)
        mkt = ff["Mkt-RF"].reindex(earn).to_numpy()
        # ---------------------------------------------------------- per-method tables
        rows = {}
        for tag, ev, p in (("ext", ev_e, p_e), ("base", ev_b, p_b)):
            for m, e in ev.items():
                r = A.summary_row(e, p, ff)
                r["sharpe_net_lo"], r["sharpe_net_hi"] = A.sharpe_ci(e.net[months], B, block, seed=1)
                h = A.market_hedged(e.net, mkt, months)
                hm = months[np.isfinite(h[months])]
                r["sharpe_hedged"] = stats.sharpe(h[hm])
                rows[(tag, m)] = r
        tab = pd.DataFrame(rows).T
        tab.index.names = ["set", "method"]
        tab.to_csv(T_DIR / f"ext_{w}_methods.csv")
        # ---------------------------------------------------------- H10: extended EW vs baseline EW
        e1, e0 = ev_e["EW"], ev_b["EW"]
        d = np.nan_to_num(e1.ic[months] - e0.ic[months])
        t_ic = stats.nw_tstat(d)
        sd = stats.sharpe_diff_test(e1.net[months], e0.net[months], B=B, block=block, seed=3)
        h1 = A.market_hedged(e1.net, mkt, months)
        h0 = A.market_hedged(e0.net, mkt, months)
        hm = months[np.isfinite(h1[months]) & np.isfinite(h0[months])]
        sdh = stats.sharpe_diff_test(h1[hm], h0[hm], B=B, block=block, seed=4)
        h10_rows.append({"window": label, "months": len(months), "ic_ext": float(np.nanmean(e1.ic[months])),
                         "ic_base": float(np.nanmean(e0.ic[months])), "ic_diff": float(d.mean()), "ic_t": t_ic,
                         "p_ic": float(2 * stats.sps.norm.sf(abs(t_ic))), "sharpe_net_ext": stats.sharpe(e1.net[months]),
                         "sharpe_net_base": stats.sharpe(e0.net[months]), "sharpe_diff": sd["diff"], "p_sharpe": sd["p_boot"],
                         "hedged_ext": stats.sharpe(h1[hm]), "hedged_base": stats.sharpe(h0[hm]),
                         "hedged_diff": sdh["diff"], "p_hedged": sdh["p_boot"]})
        # ---------------------------------------------------------- H11: complex vs extended EW (decision rule)
        tests = A.tests_vs(ev_e, "EW", B, block, seed=11)
        tests.to_csv(T_DIR / f"ext_{w}_tests_vs_ew.csv")
        complex_m = [m for m in order_e if m not in cfg_e["simple_methods"]]
        spa_raw = A.spa(ev_e, "EW", complex_m, B, block, seed=21)
        V = {m: A.vol_scaled(ev_e[m].net, months) for m in complex_m + ["EW"]}
        vm = months[np.isfinite(V["EW"][months])]
        spa_vol = stats.spa_test(np.column_stack([V[m][vm] - V["EW"][vm] for m in complex_m]), B=B, block=block,
                                 seed=22)
        spa_vol["best"] = complex_m[spa_vol["best_index"]]
        cplx = tests.loc[complex_m]
        sharpe_win = cplx[(cplx["sharpe_diff"] > 0) & (cplx["p_sharpe_holm"] < 0.05)].index.tolist()
        ic_win = cplx[(cplx["ic_diff"] > 0) & (cplx["p_ic_holm"] < 0.05)].index.tolist()
        rule = bool((sharpe_win and spa_vol["p_consistent"] < 0.05) or
                    (ic_win and spa_raw["rank_ic"]["p_consistent"] < 0.05))
        # ---------------------------------------------------------- H12: hedged
        H = {m: A.market_hedged(ev_e[m].net, mkt, months) for m in order_e}
        hmo = months[np.isfinite(H["EW"][months])]
        h12 = []
        for j, m in enumerate([x for x in order_e if x != "EW"]):
            t = stats.sharpe_diff_test(H[m][hmo], H["EW"][hmo], B=B, block=block, seed=30 + j)
            h12.append({"method": m, "hedged_sharpe": stats.sharpe(H[m][hmo]), "diff": t["diff"], "p": t["p_boot"]})
        h12 = pd.DataFrame(h12).set_index("method")
        h12["p_holm"] = stats.holm(h12["p"].to_numpy())
        h12.to_csv(T_DIR / f"ext_{w}_hedged_tests.csv")
        h12_win = h12[(h12["diff"] > 0) & (h12["p_holm"] < 0.05) & ~h12.index.isin(cfg_e["simple_methods"])]
        # ---------------------------------------------------------- descriptive: does richer information help complex methods more?
        did = []
        for m in order_e:
            if m == "EW" or m not in ev_b:
                continue
            did.append({"method": m,
                        "gain_ext_sharpe": stats.sharpe(ev_e[m].net[months]) - stats.sharpe(e1.net[months]),
                        "gain_base_sharpe": stats.sharpe(ev_b[m].net[months]) - stats.sharpe(e0.net[months]),
                        "gain_ext_ic": float(np.nanmean(ev_e[m].ic[months] - e1.ic[months])),
                        "gain_base_ic": float(np.nanmean(ev_b[m].ic[months] - e0.ic[months]))})
        did = pd.DataFrame(did).set_index("method")
        did["diff_in_diff_sharpe"] = did["gain_ext_sharpe"] - did["gain_base_sharpe"]
        did["diff_in_diff_ic"] = did["gain_ext_ic"] - did["gain_base_ic"]
        did.to_csv(T_DIR / f"ext_{w}_gain_vs_base.csv")
        imp = A.importance_table(res_e)
        fam_cols = [c for c in imp.columns if c.startswith("family:")]
        fam = imp[fam_cols].copy()
        fam.columns = [c.split(":")[1] for c in fam_cols]
        fam.to_csv(T_DIR / f"ext_{w}_importance_families.csv")
        # ---------------------------------------------------------- descriptive: subperiods (main study's boundaries, cut to the window)
        lo, hi = p_e.dates[months[0]], p_e.dates[months[-1]]
        periods = [(max(pd.Timestamp(s), lo).strftime("%Y-%m-%d"), min(pd.Timestamp(z), hi).strftime("%Y-%m-%d"))
                   for s, z in study.load_config("main")["subperiods"] if pd.Timestamp(z) >= lo]
        sp = A.subperiods({"EW (16 signals)": e0, **ev_e}, p_e, periods)
        sp.to_csv(T_DIR / f"ext_{w}_subperiods.csv", index=False)
        sp_rows = ["EW (16 signals)"] + order_e
        sp_tab = pd.concat({f"{per} {lab}": sp[sp["period"] == per].set_index("method")[col].reindex(sp_rows)
                            for per in sp["period"].unique() for col, lab in (("sharpe_net", "Sharpe"),
                                                                              ("rank_ic", "IC"))}, axis=1)
        summary[w] = {"label": label, "months": int(len(months)), "rule_met": rule, "sharpe_holm_winners": sharpe_win,
                      "ic_holm_winners": ic_win, "spa_ic": spa_raw["rank_ic"], "spa_net_raw": spa_raw["net_return"],
                      "spa_vol": spa_vol, "hedged_winners": h12_win.index.tolist()}
        # ---------------------------------------------------------- figure
        td = tests.loc[[m for m in order_e if m != "EW"], ["sharpe_diff", "sharpe_ci_lo", "sharpe_ci_hi"]].astype(float)
        F.dot_ci(td, "sharpe_diff", "sharpe_ci_lo", "sharpe_ci_hi",
                 f"Net Sharpe minus extended equal weights ({label})", "difference in annualized Sharpe ratio",
                 F_DIR / f"ext_{w}_sharpe_diff_vs_ew.png", ref=0.0)
        # ---------------------------------------------------------- markdown
        t_ext = tab.xs("ext", level="set").loc[order_e]
        md += [f"## Window {w.upper()}: {label} ({len(months)} months)", "",
               md_table(t_ext[["rank_ic", "rank_ic_t", "sharpe_gross", "sharpe_net", "sharpe_net_lo", "sharpe_net_hi",
                               "sharpe_hedged", "turnover", "alpha", "alpha_t"]].astype(float),
                        {"rank_ic": 4, "rank_ic_t": 1, "turnover": 1, "alpha_t": 1}), "",
               "Each method against extended EW (H11):", "",
               md_table(tests[["sharpe_diff", "p_sharpe", "p_sharpe_holm", "p_sharpe_rw", "ic_diff", "ic_t", "p_ic_holm",
                               "p_ic_rw"]].astype(float), {"ic_diff": 4, "ic_t": 2, "p_sharpe": 3, "p_sharpe_holm": 3,
                                                          "p_sharpe_rw": 3, "p_ic_holm": 3, "p_ic_rw": 3}), "",
               f"- SPA, best complex vs EW: rank IC best {spa_raw['rank_ic']['best']} p = "
               f"{spa_raw['rank_ic']['p_consistent']:.3f}; net return best {spa_raw['net_return']['best']} p = "
               f"{spa_raw['net_return']['p_consistent']:.3f}; volatility-scaled best {spa_vol['best']} p = "
               f"{spa_vol['p_consistent']:.3f}",
               f"- **Decision rule met: {'yes' if rule else 'no'}** (Holm winners: Sharpe {sharpe_win or 'none'}, "
               f"rank IC {ic_win or 'none'})", "",
               "Market-hedged (H12):", "", md_table(h12.astype(float), {"p": 3, "p_holm": 3}), "",
               "Gain over EW, extended set vs the same method's gain on the sixteen signals (descriptive):", "",
               md_table(did.astype(float), {"gain_ext_ic": 4, "gain_base_ic": 4, "diff_in_diff_ic": 4}), "",
               "Permutation importance by family (drop in mean rank IC):", "", md_table(fam.astype(float), 4), "",
               "Subperiods (descriptive; net Sharpe and mean rank IC; the main study's boundaries cut to the window):",
               "", md_table(sp_tab.astype(float), {c: 4 for c in sp_tab.columns if c.endswith("IC")}), ""]
    h10 = pd.DataFrame(h10_rows).set_index("window")
    h10["p_ic_holm"] = stats.holm(h10["p_ic"].to_numpy())
    h10.to_csv(T_DIR / "ext_h10.csv")
    md[4:4] = ["## H10: do the new signals improve equal weighting?", "",
               md_table(h10.astype(float), {"ic_ext": 4, "ic_base": 4, "ic_diff": 4, "ic_t": 2, "p_ic": 3,
                                            "p_ic_holm": 3, "p_sharpe": 3, "p_hedged": 3, "months": 0}), ""]
    (paths.REPORTS / "extension.md").write_text("\n".join(md), encoding="utf-8")
    (T_DIR / "ext_summary.json").write_text(json.dumps(summary, indent=1, default=str))
    export_demo(h10, summary)
    print("\n".join(md[:12]))
    print(json.dumps({k: {kk: v[kk] for kk in ("rule_met", "sharpe_holm_winners", "ic_holm_winners", "hedged_winners")}
                      for k, v in summary.items()}, indent=1))


def export_demo(h10: pd.DataFrame | None = None, summary: dict | None = None) -> None:
    """Compact extension summary for the demo's S&P 500 tab (portfolio-level numbers only). Called on its own
    (--demo-only), it reads the tables and summary that a full run saved."""
    if h10 is None:
        h10 = pd.read_csv(T_DIR / "ext_h10.csv", index_col=0)
    if summary is None:
        summary = json.loads((T_DIR / "ext_summary.json").read_text())
    out = {}
    for w, (ext, base, label) in WINDOWS.items():
        tab = pd.read_csv(T_DIR / f"ext_{w}_methods.csv", index_col=[0, 1])
        ext_rows = tab.xs("ext", level="set")
        cplx = ext_rows.drop(index=[m for m in ("EW", "HEW", "ICW") if m in ext_rows.index])
        tests = pd.read_csv(T_DIR / f"ext_{w}_tests_vs_ew.csv", index_col=0).loc[cplx.index].astype(float)
        top_sh, top_ic = tests["sharpe_diff"].idxmax(), tests["ic_diff"].idxmax()
        picks = [("16 signals", "EW", tab.loc[("base", "EW")]), (f"{'20' if w == 'a' else '23'} signals", "EW",
                                                                   tab.loc[("ext", "EW")])]
        best_sh = cplx["sharpe_net"].astype(float).idxmax()
        best_ic = cplx["rank_ic"].astype(float).idxmax()
        picks.append((picks[1][0], best_sh, ext_rows.loc[best_sh]))
        if best_ic != best_sh:
            picks.append((picks[1][0], best_ic, ext_rows.loc[best_ic]))
        r = h10.loc[label]
        out[w] = {"label": label, "months": int(summary[w]["months"]), "rule_met": bool(summary[w]["rule_met"]),
                  "hedged_winners": summary[w]["hedged_winners"],
                  "h10": {k: round(float(r[k]), 4) for k in ("ic_diff", "ic_t", "p_ic_holm", "sharpe_diff", "p_sharpe",
                                                             "hedged_diff", "p_hedged")},
                  # largest gain of any complex method over extended EW, with its Holm-adjusted p (H11)
                  "top_sharpe": {"method": top_sh, "diff": round(float(tests.loc[top_sh, "sharpe_diff"]), 3),
                                 "p_holm": round(float(tests.loc[top_sh, "p_sharpe_holm"]), 3)},
                  "top_ic": {"method": top_ic, "diff": round(float(tests.loc[top_ic, "ic_diff"]), 4),
                             "p_holm": round(float(tests.loc[top_ic, "p_ic_holm"]), 3)},
                  "spa": {"ic_best": summary[w]["spa_ic"]["best"],
                          "ic_p": round(float(summary[w]["spa_ic"]["p_consistent"]), 3),
                          "vol_best": summary[w]["spa_vol"]["best"],
                          "vol_p": round(float(summary[w]["spa_vol"]["p_consistent"]), 3)},
                  "rows": [{"set": s, "method": m, "rank_ic": round(float(v["rank_ic"]), 4),
                            "sharpe_net": round(float(v["sharpe_net"]), 3),
                            "sharpe_hedged": round(float(v["sharpe_hedged"]), 3)} for s, m, v in picks]}
    (paths.REPORTS / "demo_extension.json").write_text(json.dumps(out, indent=1), encoding="utf-8")


if __name__ == "__main__":
    main()
